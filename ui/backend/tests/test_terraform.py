def hcl_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def balanced(text: str) -> bool:
    code = re.sub(r'"(?:[^"\\]|\\.)*"', '""', re.sub(r"<<-(\w+)\n.*?\n\s*\1\n", "\n", text, flags=re.S))
    code = "\n".join(ln for ln in code.split("\n") if not ln.lstrip().startswith("#"))
    return all(code.count(a) == code.count(b) for a, b in ("{}", "[]", "()"))


