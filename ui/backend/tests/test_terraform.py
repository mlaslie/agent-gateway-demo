def test_api_terraform_demo(client):  # noqa: F811
    client.post("/api/themes/helpdesk/reset", json={"mode": "demo"})
    client.post("/api/model-armor", json={"enabled": False, "mode": "demo"})
    client.post("/api/themes/helpdesk/policies/gw-egress", json={"action": "apply", "mode": "demo"})
    client.post("/api/themes/helpdesk/policies/allow-kb", json={"action": "apply", "mode": "demo"})
    r = client.get("/api/themes/helpdesk/terraform?mode=demo")
    assert r.status_code == 200
    body = r.json()
    assert body["source"] == "simulated"
    assert body["applied"] == ["gw-egress", "allow-kb"]
    assert body["model_armor"] is False and body["include_shared"] is False
    assert set(body["files"]) == {"main.tf", "variables.tf", "README.md"}
    assert '"allow_kb"' in body["files"]["main.tf"] and "terraform_data" in body["files"]["main.tf"]
    r = client.get("/api/themes/helpdesk/terraform?mode=demo&include_shared=true")
    assert "google_network_services_agent_gateway" in r.json()["files"]["main.tf"]
    client.post("/api/themes/helpdesk/reset", json={"mode": "demo"})


